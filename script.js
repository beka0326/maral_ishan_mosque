const kaspiLink = "https://pay.kaspi.kz/pay/ixvk3h7";

function applyLanguage(lang) {
  const dict = translations[lang];
  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (dict[key]) {
      element.textContent = dict[key];
    }
  });

  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.classList.toggle("active", btn.dataset.lang === lang);
  });

  localStorage.setItem("site_lang", lang);
}

function setupLanguageSwitcher() {
  const saved = localStorage.getItem("site_lang") || "kk";
  applyLanguage(saved);

  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.addEventListener("click", () => {
      applyLanguage(btn.dataset.lang);
    });
  });
}

function setupMobileMenu() {
  const toggle = document.getElementById("menuToggle");
  const menu = document.getElementById("mobileMenu");

  if (!toggle || !menu) return;

  toggle.addEventListener("click", () => {
    const isOpen = menu.classList.toggle("open");
    toggle.setAttribute("aria-expanded", String(isOpen));
  });

  menu.querySelectorAll("a").forEach((link) => {
    link.addEventListener("click", () => {
      menu.classList.remove("open");
      toggle.setAttribute("aria-expanded", "false");
    });
  });
}

function setupDonationPresets() {
  const amountInput = document.getElementById("amountInput");
  const note = document.getElementById("donateNote");
  const presetButtons = document.querySelectorAll(".preset-btn");

  presetButtons.forEach((button) => {
    button.addEventListener("click", () => {
      presetButtons.forEach((btn) => btn.classList.remove("active"));
      button.classList.add("active");

      const amount = button.dataset.amount;
      amountInput.value = amount;

      const lang = localStorage.getItem("site_lang") || "kk";
      note.textContent =
        lang === "kk"
          ? `Таңдалған сома: ${Number(amount).toLocaleString("ru-RU")} ₸. Төлем Kaspi бетінде жалғасады.`
          : `Выбранная сумма: ${Number(amount).toLocaleString("ru-RU")} ₸. Оплата продолжается на странице Kaspi.`;
    });
  });
}

function setupCopyLink() {
  const copyBtn = document.getElementById("copyLinkBtn");
  const note = document.getElementById("donateNote");

  if (!copyBtn) return;

  copyBtn.addEventListener("click", async () => {
    const lang = localStorage.getItem("site_lang") || "kk";

    try {
      await navigator.clipboard.writeText(kaspiLink);
      note.textContent =
        lang === "kk"
          ? "Kaspi сілтемесі көшірілді."
          : "Ссылка Kaspi скопирована.";
    } catch (error) {
      note.textContent =
        lang === "kk"
          ? "Сілтемені көшіру мүмкін болмады."
          : "Не удалось скопировать ссылку.";
    }
  });
}

function setupDonateLink() {
  const donateLink = document.getElementById("kaspiDonateLink");
  const amountInput = document.getElementById("amountInput");

  if (!donateLink || !amountInput) return;

  donateLink.addEventListener("click", () => {
    const value = Number(amountInput.value || 0);
    if (value > 0) {
      localStorage.setItem("selected_donation_amount", String(value));
    }
  });
}

document.addEventListener("DOMContentLoaded", () => {
  setupLanguageSwitcher();
  setupMobileMenu();
  setupDonationPresets();
  setupCopyLink();
  setupDonateLink();
});